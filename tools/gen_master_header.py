#!/usr/bin/env python3
"""Generate tools/vault_master.h — obfuscated embedded master key.

Usage:
  python3 gen_master_header.py --master=<64 hex chars> --out=<path>

Obfuscation (matched by decode_master() in vault.cpp):
  VA[i] = ror8(master[i], (i%3)+1) ^ VB[i]
  VB[i] = random byte (deterministic per run, stored)
  runtime: master[i] = rol8(VA[i] ^ VB[i], (i%3)+1)
"""
import argparse
import random
import secrets


def ror8(x, n):
    return ((x >> n) | (x << (8 - n))) & 0xFF


def rol8(x, n):
    return ((x << n) | (x >> (8 - n))) & 0xFF


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--master", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    master = bytes.fromhex(args.master.strip())
    if len(master) != 32:
        raise SystemExit("master must be 32 bytes (64 hex)")

    # Deterministic PRNG so reruns with same master produce same arrays
    rng = random.Random(int.from_bytes(master, "big") ^ 0x5A5A5A5A)
    vb = bytes(rng.randrange(256) for _ in range(32))
    va = bytes(
        ror8(master[i], (i % 3) + 1) ^ vb[i] for i in range(32)
    )

    def carr(name, data):
        hex_bytes = ",".join(f"0x{b:02x}" for b in data)
        return f"static const uint8_t {name}[32] = {{{hex_bytes}}};\n"

    out = []
    out.append("// AUTO-GENERATED by tools/gen_master_header.py — DO NOT COMMIT\n")
    out.append("#pragma once\n#include <cstdint>\n")
    out.append("#define VAULT_HAS_EMBEDDED_MASTER 1\n")
    out.append(carr("VA", va))
    out.append(carr("VB", vb))
    out.append(
        "static inline void decode_master(uint8_t out[32]) {\n"
        "    for (int i = 0; i < 32; i++) {\n"
        "        uint8_t v = (uint8_t)(VA[i] ^ VB[i]);\n"
        "        int n = (i % 3) + 1;\n"
        "        out[i] = (uint8_t)((v << n) | (v >> (8 - n)));\n"
        "    }\n"
        "}\n"
    )

    with open(args.out, "w") as f:
        f.write("".join(out))

    # Self-check
    decoded = bytearray(32)
    for i in range(32):
        v = va[i] ^ vb[i]
        n = (i % 3) + 1
        decoded[i] = rol8(v, n)
    assert bytes(decoded) == master, "self-check failed"
    print(f"wrote {args.out} (self-check OK)")


if __name__ == "__main__":
    main()
